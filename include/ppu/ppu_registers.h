/*
 * ppu_registers.h - Alamat dan bit field register PPU.
 */
#ifndef TINYNES_PPU_PPU_REGISTERS_H
#define TINYNES_PPU_PPU_REGISTERS_H

#define PPU_REG_CTRL 0U
#define PPU_REG_MASK 1U
#define PPU_REG_STATUS 2U
#define PPU_REG_OAMADDR 3U
#define PPU_REG_OAMDATA 4U
#define PPU_REG_SCROLL 5U
#define PPU_REG_ADDR 6U
#define PPU_REG_DATA 7U

/* PPUCTRL ($2000) */
#define PPU_CTRL_NAMETABLE_MASK 0x03U
#define PPU_CTRL_INCREMENT32 0x04U
#define PPU_CTRL_SPRITE_TABLE 0x08U
#define PPU_CTRL_BG_TABLE 0x10U
#define PPU_CTRL_SPRITE_SIZE 0x20U
#define PPU_CTRL_NMI_ENABLE 0x80U

/* PPUMASK ($2001) */
#define PPU_MASK_GRAYSCALE 0x01U
#define PPU_MASK_BG_LEFT 0x02U
#define PPU_MASK_SPRITE_LEFT 0x04U
#define PPU_MASK_BG_ENABLE 0x08U
#define PPU_MASK_SPRITE_ENABLE 0x10U
#define PPU_MASK_RENDERING (PPU_MASK_BG_ENABLE | PPU_MASK_SPRITE_ENABLE)

/* PPUSTATUS ($2002) */
#define PPU_STATUS_OVERFLOW 0x20U
#define PPU_STATUS_SPRITE0 0x40U
#define PPU_STATUS_VBLANK 0x80U

/* Posisi bit internal loopy register v/t. */
#define PPU_COARSE_X_MASK 0x001FU
#define PPU_COARSE_Y_MASK 0x03E0U
#define PPU_NAMETABLE_MASK 0x0C00U
#define PPU_FINE_Y_MASK 0x7000U

#endif /* TINYNES_PPU_PPU_REGISTERS_H */
